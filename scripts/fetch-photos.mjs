// Pulls real keyboard photography from Openverse (CC0, public domain, CC BY,
// CC BY-SA), downscales it with ffmpeg and writes a manifest the site imports.
// Every photo keeps its title, creator and licence so the credit can be shown.
//
//   node scripts/fetch-photos.mjs
//
// Re-running only fetches what is missing, so it is safe to interrupt.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\//, '');
const OUT = join(ROOT, 'public', 'photos');
const MANIFEST = join(ROOT, 'src', 'data', 'photos.ts');
const LICENSE = 'cc0,pdm,by,by-sa';

// slug: search terms, how many to keep. Brand slugs feed that brand's page.
const QUERIES = [
  ['keychron', 'Keychron keyboard', 3],
  ['razer', 'Razer keyboard', 3],
  ['logitech', 'Logitech keyboard', 3],
  ['ducky', 'Ducky keyboard', 2],
  ['akko', 'Akko keyboard', 2],
  ['corsair', 'Corsair keyboard', 2],
  ['aula', 'Aula keyboard', 2],
  ['nuphy', 'NuPhy keyboard', 2],
  ['hhkb', 'HHKB keyboard', 2],
  ['topre', 'Topre Realforce keyboard', 2],
  ['leopold', 'Leopold keyboard', 2],
  ['varmilo', 'Varmilo keyboard', 2],
  ['glorious', 'GMMK keyboard', 2],
  ['wooting', 'Wooting keyboard', 2],
  ['steelseries', 'SteelSeries keyboard', 2],
  ['mode', 'custom mechanical keyboard', 3],
  ['switch-linear', 'Cherry MX red switch', 2],
  ['switch-tactile', 'Cherry MX brown switch', 2],
  ['switch-clicky', 'Cherry MX blue switch', 2],
  ['switch-dome', 'Topre switch dome', 2],
  ['keycaps', 'mechanical keyboard keycaps', 4],
  ['desk', 'keyboard desk setup', 4],
  ['workshop', 'mechanical keyboard meetup', 4],
  ['vintage', 'vintage computer keyboard', 3],
  ['collection', 'keyboard collection shelf', 2],
];

const size = (p) => (existsSync(p) ? readFileSync(p).length : 0);

function get(url) {
  const tmp = join(OUT, '.query.json');
  execFileSync('curl.exe', ['-sS', '-L', '--max-time', '60', '-A', 'keyboard-atlas/1.0 (open source keyboard catalog)', '-o', tmp, url], {
    stdio: 'inherit',
  });
  return JSON.parse(readFileSync(tmp, 'utf8'));
}

function download(url, dest) {
  execFileSync('curl.exe', ['-sS', '-L', '--max-time', '90', '-A', 'keyboard-atlas/1.0', '-o', dest, url], {
    stdio: 'inherit',
  });
}

mkdirSync(OUT, { recursive: true });

const photos = [];
for (const [slug, query, want] of QUERIES) {
  let kept = 0;
  try {
    const data = get(
      `https://api.openverse.org/v1/images/?q=${encodeURIComponent(query)}&license=${LICENSE}` +
        `&page_size=20&mature=false&extension=jpg,jpeg,png,webp`,
    );
    for (const hit of data.results ?? []) {
      if (kept >= want) break;
      const w = hit.width ?? 0;
      const h = hit.height ?? 0;
      if (w < 900 || !h) continue;
      const aspect = w / h;
      if (aspect < 1.1 || aspect > 2.6) continue;
      if (!hit.url) continue;

      const dest = join(OUT, `${slug}-${kept + 1}.jpg`);
      if (!size(dest)) {
        const raw = join(OUT, '.raw');
        download(hit.url, raw);
        if (size(raw) < 20000) continue;
        execFileSync(
          'ffmpeg',
          ['-y', '-loglevel', 'error', '-i', raw, '-vf', "scale='min(1400,iw)':-2", '-q:v', '4', dest],
          { stdio: 'inherit' },
        );
      }
      photos.push({
        slug,
        file: `${slug}-${kept + 1}.jpg`,
        title: (hit.title ?? 'Untitled').slice(0, 90),
        creator: hit.creator ?? 'Unknown',
        license: `${(hit.license ?? '').toUpperCase()} ${hit.license_version ?? ''}`.trim(),
        licenseUrl: hit.license_url ?? '',
        source: hit.foreign_landing_url ?? hit.url,
      });
      kept++;
    }
  } catch (err) {
    console.error(`skip ${slug}: ${err.message}`);
  }
  console.log(`${slug}: ${kept}`);
  // The anonymous pool allows 20 requests a minute.
  await new Promise((r) => setTimeout(r, 3500));
}

writeFileSync(
  MANIFEST,
  `// Real keyboard photography, generated by scripts/fetch-photos.mjs.
// Every entry keeps its title, creator and licence. Do not strip the credit.

export type Photo = {
  slug: string;
  src: string;
  title: string;
  creator: string;
  license: string;
  licenseUrl: string;
  source: string;
};

export const PHOTOS: Photo[] = ${JSON.stringify(
    photos.map((p) => ({ ...p, src: `/photos/${p.file}` })).map(({ file, ...p }) => p),
    null,
    2,
  )};

export const photo = (slug: string, n = 0): Photo | undefined =>
  PHOTOS.filter((p) => p.slug === slug)[n];
`,
);

const bySlug = new Map();
for (const p of photos) {
  const list = bySlug.get(p.slug) ?? [];
  list.push(p);
  bySlug.set(p.slug, list);
}
for (const [slug, list] of bySlug) {
  console.log(`${slug}: ${list.map((p) => p.file).join(', ')}`);
}
